object I18n {
    fun resolveUiLanguage(uiLanguage: String): String {
        if (uiLanguage != "auto") return uiLanguage
        val lang = Locale.getDefault().language
        return when {
            lang.startsWith("zh") -> "zh"
            lang.startsWith("ja") -> "ja"
            lang.startsWith("fr") -> "fr"
            lang.startsWith("de") -> "de"
            lang.startsWith("ru") -> "ru"
            else -> "en"
        }
    }

    fun t(uiLanguage: String, key: String, vararg args: Any): String {
        val lang = resolveUiLanguage(uiLanguage)
        var str = locales[lang]?.get(key) ?: locales["en"]?.get(key) ?: key
        args.forEachIndexed { i, arg -> str = str.replace("{$i}", arg.toString()) }
        return str
    }
