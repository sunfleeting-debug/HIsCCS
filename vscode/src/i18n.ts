// ── Get UI language (manual override > VS Code) ──────

function getUILanguage(): string {
	try {
		const cfg = vscode.workspace.getConfiguration('cmg');
		const uiLang = cfg.uiLanguage;
		if (uiLang && uiLang !== 'auto') return uiLang;

		const lang = vscode.env.language;
		if (lang.startsWith('zh')) return 'zh';
		if (lang.startsWith('ja')) return 'ja';
		if (lang.startsWith('fr')) return 'fr';
		if (lang.startsWith('de')) return 'de';
		if (lang.startsWith('ru')) return 'ru';
		return 'en';
	} catch {
		return 'en';
	}
}

// ── Translation function ─────────────────────────────

export function t(key: string, ...args: (string | number)[]): string {
	const lang = getUILanguage();
	let str = locales[lang]?.[key] ?? locales.en[key];
	if (str === undefined) {
		console.warn(`[HisCCS] Missing i18n key: ${key} for locale: ${lang}`);
		return key;
	}
	if (args.length > 0) {
		args.forEach((arg, i) => {
			str = str!.replace(`{${i}}`, String(arg));
		});
	}
	return str!;
}
